#!/usr/bin/env python3
# Generates qml/emoji/EmojiData.js from Unicode's public emoji-test.txt
# (https://unicode.org/Public/emoji/latest/emoji-test.txt, UTS #51).
# Usage: gen-emoji.py emoji-test.txt > EmojiData.js
#
# The groups of emoji-test.txt map 1:1 to the stock tabs (Smileys & Emotion,
# People & Body, Animals & Nature, Food & Drink, Travel & Places, Activities,
# Objects, Symbols, Flags); "Component" is left out (skin-tone swatches, hair).
# Only fully-qualified sequences are kept. A sequence with skin-tone modifiers
# (U+1F3FB..1F3FF) becomes a variant of the same sequence without them.
# Code points are written as hex joined by "." so the file is plain ASCII.
import re
import sys

GROUPS = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "animals",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
TONES = range(0x1F3FB, 0x1F400)

def key(cps):
    return tuple(c for c in cps if c != 0xFE0F and c not in TONES)

def main(path):
    version = date = ""
    cats = {}
    order = []
    group = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"# Version: (\S+)", line)
        if m:
            version = m.group(1)
        m = re.match(r"# Date: (.*)", line)
        if m:
            date = m.group(1)
        m = re.match(r"# group: (.*)", line)
        if m:
            group = m.group(1)
            continue
        if not line or line.startswith("#"):
            continue
        m = re.match(r"([0-9A-F ]+?)\s*; (\S+)\s+# \S+ E(\d+)\.(\d+) ", line)
        if not m or m.group(2) != "fully-qualified" or group not in GROUPS:
            continue
        cps = [int(x, 16) for x in m.group(1).split()]
        ver = int(m.group(3)) * 10 + int(m.group(4))
        cid = GROUPS[group]
        if cid not in cats:
            cats[cid] = {"order": [], "items": {}}
            order.append(cid)
        c = cats[cid]
        k = key(cps)
        toned = any(x in TONES for x in cps)
        if k not in c["items"]:
            c["items"][k] = {"base": None, "ver": ver, "variants": []}
            c["order"].append(k)
        it = c["items"][k]
        if toned:
            it["variants"].append(cps)
            it["ver"] = max(it["ver"], ver) if it["base"] is None else it["ver"]
        else:
            it["base"] = cps
            it["ver"] = ver
    out = []
    out.append("/*")
    out.append(" * GENERATED by gen-emoji.py from Unicode's emoji-test.txt, Version %s (%s)." % (version, date))
    out.append(" * Do not edit; run: gen-emoji.py emoji-test.txt > EmojiData.js")
    out.append(" *")
    out.append(" * Emoji data: Copyright (c) Unicode, Inc., under the Unicode License v3 / Terms of Use")
    out.append(" * (https://www.unicode.org/terms_of_use.html). Only code point sequences and their")
    out.append(" * Emoji version are kept; no names, no images.")
    out.append(" *")
    out.append(" * Format: one string per category; entries separated by \"|\"; an entry is")
    out.append(" * \"HEX.HEX:VER[,VARIANT,...]\": the code points of the emoji in hex, the Emoji version x10")
    out.append(" * (E13.1 = 131), then the skin-tone variants (code points only).")
    out.append(" */")
    out.append(".pragma library")
    out.append("")
    out.append('var unicodeVersion = "%s"' % version)
    out.append("var categories = [")
    n_base = n_var = 0
    for i, cid in enumerate(order):
        c = cats[cid]
        entries = []
        for k in c["order"]:
            it = c["items"][k]
            base = it["base"]
            if base is None:
                # a toned sequence without a toneless form: the first variant leads
                base = it["variants"][0]
                vars_ = it["variants"][1:]
            else:
                vars_ = it["variants"]
            s = ".".join("%X" % x for x in base) + ":%d" % it["ver"]
            for v in vars_:
                s += "," + ".".join("%X" % x for x in v)
            entries.append(s)
            n_base += 1
            n_var += len(vars_)
        out.append('    { id: "%s", data: "%s" }%s' % (cid, "|".join(entries), "," if i + 1 < len(order) else ""))
    out.append("]")
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("categories %d, emoji %d, variants %d\n" % (len(order), n_base, n_var))

main(sys.argv[1])
