// "word: a b c" rows -> { word: [a, b, c] }
function _table(rows) {
    var t = {}
    for (var i = 0; i < rows.length; i++) {
        var c = rows[i].indexOf(":")
        var key = rows[i].substring(0, c)
        var list = rows[i].substring(c + 1).trim().split(" ")
        // a word listed twice: the later followers go after the earlier ones
        var have = t[key] || (t[key] = [])
        for (var j = 0; j < list.length; j++) {
            if (list[j].length > 0 && have.indexOf(list[j]) < 0)
                have.push(list[j])
        }
    }
    return t
}

